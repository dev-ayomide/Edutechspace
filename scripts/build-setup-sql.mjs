// Concatenates supabase/migrations/*.sql, in order, into one file you can paste into the Supabase SQL editor:
//   supabase/setup/all-migrations.sql
// Run after any migration change:  npm run setup:sql
// `--check` exits non-zero if the bundle is out of date (used by the test suite).
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'

const DIR = 'supabase/migrations'
const OUT = 'supabase/setup/all-migrations.sql'

export async function buildBundle() {
  const files = (await readdir(DIR)).filter((f) => f.endsWith('.sql')).sort()
  const parts = [
    '-- RUNTech Space: complete database setup (generated by scripts/build-setup-sql.mjs; do not edit).',
    '-- Paste this whole file into Supabase > SQL Editor > New query, and click Run. It runs in one transaction,',
    '-- so if anything fails nothing is applied. Run it ONCE, on an empty project.',
    '',
    'begin;',
    '',
  ]
  for (const f of files) {
    const body = (await readFile(path.join(DIR, f), 'utf8')).trim()
    parts.push(`-- ============================== ${f} ==============================`, '', body, '')
  }
  parts.push('commit;', '')
  return parts.join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const bundle = await buildBundle()
  if (process.argv.includes('--check')) {
    const current = await readFile(OUT, 'utf8').catch(() => '')
    if (current !== bundle) {
      console.error(`${OUT} is out of date. Run: npm run setup:sql`)
      process.exit(1)
    }
    console.log('setup bundle is up to date')
  } else {
    await mkdir(path.dirname(OUT), { recursive: true })
    await writeFile(OUT, bundle)
    console.log(`wrote ${OUT} (${bundle.split('\n').length} lines)`)
  }
}
